export function getCurrentSession(): 'Asian' | 'London' | 'NewYork' {
  const h = new Date().getUTCHours();
  if (h >= 0 && h < 8) return 'Asian';
  if (h >= 7 && h < 16) return 'London';
  return 'NewYork';
}

