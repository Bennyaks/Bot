/**
 * The original constants (0.00035 drift, 0.0008 noise, 0.0004 wick) were
 * absolute price units tuned for EURUSD trading around 1.084 — applied
 * unchanged to USDJPY (~155), XAUUSD (~2385), NAS100 (~19200) or BTCUSD
 * (~64500) they'd be meaningless (a candle series that never visibly moves).
 * Expressed as a ratio of the original base price, they become a %-of-price
 * move that scales correctly to any instrument's price level when combined
 * with that instrument's volatilityFactor (see lib/instruments.ts).
 */
const REFERENCE_BASE = 1.084;
const DRIFT_RATIO = 0.00035 / REFERENCE_BASE;
const NOISE_RATIO = 0.0008 / REFERENCE_BASE;
const WICK_RATIO = 0.0004 / REFERENCE_BASE;

export function generateCandles(count = 80, base = 1.084, volatilityFactor = 1): Candle[] {
  const candles: Candle[] = [];
  let price = base;
  const now = Date.now();
  const driftScale = base * DRIFT_RATIO * volatilityFactor;
  const noiseScale = base * NOISE_RATIO * volatilityFactor;
  const wickScale = base * WICK_RATIO * volatilityFactor;
  for (let i = count; i >= 0; i--) {
    const drift = (Math.sin(i / 8) + Math.cos(i / 13)) * driftScale;
    const noise = (Math.random() - 0.48) * noiseScale;
    const open = price;
    const close = price + drift + noise;
    const high = Math.max(open, close) + Math.random() * wickScale;
    const low = Math.min(open, close) - Math.random() * wickScale;
    const volume = 800 + Math.random() * 1400 + (i < 5 ? 900 : 0);
    candles.push({
      time: now - i * 15 * 60 * 1000,
      open,
      high,
      low,
      close,
      volume,
    });
    price = close;
  }
  return candles;
}

